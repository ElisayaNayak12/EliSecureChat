// Generates interoperability test vectors for the Flutter app FROM THE WEB APP'S OWN CRYPTO CODE.
// Run from the repo root:  node apps/flutter_app/tool/gen_vectors.mjs
// (Node 22.18+ / 24 runs the .ts import directly via type stripping.)
// The keys here are throwaway test keys, used only by the tests.
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { encryptEnvelope, serialize, safetyCode, b64 } from "../../web/src/e2ee/envelope.ts";

const here = dirname(fileURLToPath(import.meta.url));
const subtle = globalThis.crypto.subtle;
const b64url = (s) => b64.from(Uint8Array.from(Buffer.from(s, "base64url")));

async function device(deviceId) {
  const agreement = await subtle.generateKey({ name: "ECDH", namedCurve: "P-256" }, true, ["deriveBits"]);
  const signing = await subtle.generateKey({ name: "ECDSA", namedCurve: "P-256" }, true, ["sign", "verify"]);
  const raw = async (k) => b64.from(await subtle.exportKey("raw", k));
  const jwk = async (k) => subtle.exportKey("jwk", k);
  return {
    keys: { deviceId, agreement, signing },
    pub: { deviceId, agreementKey: await raw(agreement.publicKey), signingKey: await raw(signing.publicKey) },
    priv: { agreementD: b64url((await jwk(agreement.privateKey)).d), signingD: b64url((await jwk(signing.privateKey)).d) },
    jwk: { agreement: await jwk(agreement.privateKey), signing: await jwk(signing.privateKey) },
  };
}

const chatId = "chat-1f0c2d7e-3c49-4d1b-9a55-2f0e6b7d8a90";
const senderId = "user-web-sender";
const recipientId = "user-flutter";
const webSender = await device("dev-web-0001-aaaa");
const flutterDevice = await device("dev-flutter-0002-bbbb");
const otherDevice = await device("dev-other-0003-cccc");
const nodeRecipient = await device("dev-node-verify-0004"); // the Dart test encrypts to this; verify script decrypts

const messages = [];
for (const plaintext of ["Hello from the web app", "नमस्ते 👋 — unicode, emoji and \"quotes\" \\ /slashes/", ""]) {
  if (!plaintext) continue;
  const env = await encryptEnvelope({ plaintext, chatId, senderId, sender: webSender.keys, recipients: [webSender.pub, flutterDevice.pub, otherDevice.pub].map((p) => ({ ...p, userId: "x" })) });
  messages.push({ plaintext, content: serialize(env) });
}
// One message NOT sealed for the Flutter device (it must report NOT_FOR_THIS_DEVICE).
const notMine = await encryptEnvelope({ plaintext: "not for you", chatId, senderId, sender: webSender.keys, recipients: [{ ...otherDevice.pub, userId: "x" }] });

const safetyA = { userId: senderId, signingKeys: [webSender.pub.signingKey] };
const safetyB = { userId: recipientId, signingKeys: [flutterDevice.pub.signingKey, otherDevice.pub.signingKey] };

const vectors = {
  note: "Generated by tool/gen_vectors.mjs from apps/web/src/e2ee/envelope.ts. Test-only keys.",
  chatId,
  senderId,
  recipientId,
  webSender: webSender.pub,
  flutterDevice: { ...flutterDevice.pub, ...flutterDevice.priv },
  messages,
  notMine: serialize(notMine),
  safety: { a: safetyA, b: safetyB, code: await safetyCode(safetyA, safetyB) },
  nodeRecipient: { ...nodeRecipient.pub, jwk: nodeRecipient.jwk },
};
const out = join(here, "..", "test", "fixtures", "web_vectors.json");
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, JSON.stringify(vectors, null, 2));
console.log(`wrote ${out}: ${messages.length} messages, safety code ${vectors.safety.code.slice(0, 11)}…`);
